"""Reproducible DSP lookup tables; Python standard library only."""
import math
from pathlib import Path

def generate():
    tables = {
        'exp2_filter': [round(2**(-7+i/512)*2147483647) for i in range(3585)],
        'exp2_tune': [round(2**(-4+i/4096)*2147483647) for i in range(16385)],
        'envelope_keep': [round(math.exp(-.004*(1-i/1024))*2147483647) for i in range(1025)],
        'tanh_audio': [round(math.tanh(i/256)*2**23) for i in range(4097)],
        'tanh_fast': [round(math.tanh(i/4096)*2**23) for i in range(32769)],
        'blep_reciprocal': [min(2147483647,round(2**61/(2**30+i*2**18))) for i in range(4097)],
        'sat_compensation': [round(1/(1+1.5*i/1024)*2147483647) for i in range(1025)],
        'drive_kernel': [round(x*2147483647) for x in [.013475,.097598,.235621,.306612,.235621,.097598,.013475]],
    }
    lines=['// Generated by generators/tables.py. Do not edit.', '#pragma once', '#include <opxy/audio.hpp>', 'namespace acid { namespace tables {']
    for name, values in tables.items():
        lines.append('static const opxy::i32 '+name+'['+str(len(values))+'] = {')
        lines.extend('    '+', '.join(map(str,values[i:i+8]))+',' for i in range(0,len(values),8))
        lines.append('};')
    lines.append('}} // namespace acid::tables')
    return '\n'.join(lines)+'\n'

if __name__=='__main__':
    (Path(__file__).resolve().parents[1]/'tables.h').write_text(generate())
