"""Reproducible DSP lookup tables; Python standard library only."""
import math
from pathlib import Path

def generate():
    tables = {
        'exp2_filter': ([round(2**(-7+3*i/128)*16777215) for i in range(129)] +
                        [round(2**(-4+i/320)*16777215) for i in range(1,961)] +
                        [round(2**(-1+i/352)*16777215) for i in range(1,353)]),
        'envelope_keep': [round(math.exp(-.004*(1-i/128))*2147483647) for i in range(129)],
        'tanh_audio': [round(math.tanh(i/256)*2**23) for i in range(4097)],
        'tanh_fast': [round(math.tanh(i/32)*2**23) for i in range(257)],
        'blep_reciprocal': [min(2147483647,round(2**61/(2**30+i*2**18))) for i in range(4097)],
        'sat_compensation': [round(1/(1+1.5*i/128)*2147483647) for i in range(129)],
        'drive_kernel': [round(x*2147483647) for x in [.013475,.097598,.235621,.306612,.235621,.097598,.013475]],
    }
    lines=['// Generated by generators/tables.py. Do not edit.', '#pragma once', '#include <opxy/audio.hpp>', 'namespace acidxy { namespace tables {']
    for name, values in tables.items():
        if name == 'exp2_filter':
            packed = [byte for value in values for byte in (value & 255, (value >> 8) & 255, (value >> 16) & 255)]
            lines.append('static const opxy::u8 '+name+'['+str(len(packed))+'] = {')
            lines.extend('    '+', '.join(map(str,packed[i:i+16]))+',' for i in range(0,len(packed),16))
        else:
            lines.append('static const opxy::i32 '+name+'['+str(len(values))+'] = {')
            lines.extend('    '+', '.join(map(str,values[i:i+8]))+',' for i in range(0,len(values),8))
        lines.append('};')
    lines.append('}} // namespace acidxy::tables')
    return '\n'.join(lines)+'\n'

if __name__=='__main__':
    (Path(__file__).resolve().parents[1]/'tables.h').write_text(generate())

